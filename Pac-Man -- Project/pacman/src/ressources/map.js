// ======================================
// MAP MANAGER
// ======================================

export const maps = [level1, level2, level3];

export let currentLevelIndex = 0;
export let map = maps[currentLevelIndex];

export function switchLevel(index) {
    if (index >= 0 && index < maps.length) {
        currentLevelIndex = index;
        map = maps[currentLevelIndex];
        return true;
    }

    return false;
}

export function getCurrentLevel() {
    return currentLevelIndex + 1;
}

// ======================================
// PAC-MAN COLLISION
// ======================================

export function isWall(x, y) {
    const gridX = Math.floor(x + 0.5);
    const gridY = Math.floor(y + 0.5);

    // Horizontal tunnel
    if (
        gridY === TUNNEL_ROW &&
        (gridX < 0 || gridX >= map[0].length)
    ) {
        return false;
    }

    // Map boundaries
    if (
        gridX < 0 ||
        gridX >= map[0].length ||
        gridY < 0 ||
        gridY >= map.length
    ) {
        return true;
    }

    return map[gridY][gridX] === TileType.WALL;
}

// ======================================
// GHOST COLLISION
// ======================================

export function isGhostWall(x, y) {
    const gridX = Math.round(x);
    const gridY = Math.round(y);

    // Horizontal tunnel
    if (
        gridY === TUNNEL_ROW &&
        (gridX < 0 || gridX >= map[0].length)
    ) {
        return false;
    }

    // Map boundaries
    if (
        gridX < 0 ||
        gridX >= map[0].length ||
        gridY < 0 ||
        gridY >= map.length
    ) {
        return true;
    }

    // Pac-Man's four-tile safe zone
    if (
        GHOST_HOUSE_SAFE_TILES.some(
            tile => tile.x === gridX && tile.y === gridY
        )
    ) {
        return true;
    }

    return map[gridY][gridX] === TileType.WALL;
}